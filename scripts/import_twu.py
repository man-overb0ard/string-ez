"""Rebuild local TWU data: python scripts/import_twu.py (standard library only).
Original worksheet values are archived in data/twu/source.json. Never execute cell text.
"""
import collections
import json
import math
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'data/twu/source.json'
raw = json.loads(SOURCE.read_text())
headers, *values = raw['rows']
mapping = json.loads((ROOT / 'data/twu/model-map.json').read_text())
counts = collections.Counter(row[0] for row in values if row[0])
normalized, issues, runtime = [], [], []
fields = {
    'nominal': ('Gauge Nominal (mm)', 1, 1.6),
    'actual': ('Gauge Acutal (mm)', 1, 1.6),
    'stiffness': ('Stiffness (lb/in)', 1, 500),
    'loss': ('Tension Loss (%)', 0, 100),
    'energy': ('Energy Return (%)', 0, 100),
    'stringCOF': ('String/String COF', 0.001, 1),
    'ballCOF': ('String/Ball COF', 0.001, 1),
    'spin': ('Spin Potential', 0.001, 30),
    'dwell': ('Dwell Time (ms)', 0.001, 100),
    'deflection': ('Deflection (mm)', 0.001, 100),
    'staticLoss': ('Static Loss lbs.', 0, 51),
    'stabilizationLoss': ('Stabilization Loss (lbs)', 0, 51),
}
for row_number, cells in enumerate(values, 2):
    row = dict(zip(headers, cells))
    if not row['String']:
        continue
    record = {'row': row_number, 'name': row['String'], 'model': mapping.get(row['String']),
              'tension': row['Ref. Ten. (lbs)'], 'speed': row['Swing Speed'], 'material': row['Material']}
    for target, (column, minimum, maximum) in fields.items():
        value = row[column]
        try:
            number = float(value)
            valid = math.isfinite(number) and minimum <= number <= maximum
        except (TypeError, ValueError):
            valid = False
        record[target] = number if valid else None
        if not valid and value not in (None, '', 'NA', 'N/A'):
            issues.append({'row': row_number, 'field': column, 'raw': value, 'action': 'quarantined'})
    if record['nominal'] is None:
        # Recover only an explicit millimetre value from the original name, never 16/17/18 labels.
        match = re.search(r'\b(1\.[0-9]{2,3})\b', record['name'])
        if match and 1 <= float(match[1]) <= 1.6:
            record['nominal'] = float(match[1])
            issues.append({'row': row_number, 'field': 'Gauge Nominal (mm)', 'action': 'recovered_from_explicit_name', 'value': record['nominal']})
    record['duplicate'] = counts[record['name']] > 1
    if record['duplicate']:
        issues.append({'row': row_number, 'field': 'String', 'action': 'duplicate_name_excluded_from_runtime'})
    normalized.append(record)
    if record['model'] and record['nominal'] is not None and not record['duplicate'] and record['tension'] == 51 and record['speed'] == 'Fast':
        runtime.append({key: record[key] for key in ['row', 'name', 'model', 'nominal', 'stiffness', 'loss', 'energy', 'stringCOF', 'ballCOF', 'spin', 'dwell', 'deflection']})
report = {'source': raw['fileName'], 'workbookSha256': raw['workbookSha256'], 'sourceRows': len(normalized),
          'mappedModels': len(set(mapping.values())), 'runtimeModels': len({r['model'] for r in runtime}),
          'runtimeRows': len(runtime), 'conditions': [{'tensionLb': 51, 'swingSpeed': 'Fast'}],
          'issues': issues, 'modelsWithoutRuntimeData': sorted(set(mapping.values()) - {r['model'] for r in runtime})}
(ROOT / 'data/twu/normalized.json').write_text(json.dumps(normalized, ensure_ascii=False, indent=2)+'\n')
(ROOT / 'data/twu/import-report.json').write_text(json.dumps(report, ensure_ascii=False, indent=2)+'\n')
header = '''// Generated by scripts/import_twu.py. Source: user-provided TWU workbook; see data/twu/import-report.json.
export type TwuRecord = { row: number; name: string; model: string; nominal: number; stiffness: number | null; loss: number | null; energy: number | null; stringCOF: number | null; ballCOF: number | null; spin: number | null; dwell: number | null; deflection: number | null }
export const twuRecords: readonly TwuRecord[] = [
'''
calibration = {key: [min(r[key] for r in normalized if r[key] is not None and r['tension']==51 and r['speed']=='Fast'), max(r[key] for r in normalized if r[key] is not None and r['tension']==51 and r['speed']=='Fast')] for key in ['stiffness','loss','spin','stringCOF']}
header += 'export const twuRanges = '+json.dumps(calibration)+' as const\n'
# Keep the generated array opening after the calibration declaration.
header = header.replace('export const twuRecords: readonly TwuRecord[] = [\n', '') + 'export const twuRecords: readonly TwuRecord[] = [\n'
(ROOT / 'src/twuData.ts').write_text(header+'\n'.join('  '+json.dumps(r, ensure_ascii=False, separators=(',', ':'))+',' for r in runtime)+'\n]\n')
print(json.dumps({k:v for k,v in report.items() if k!='issues'}, ensure_ascii=False))
